import 'package:flutter_riverpod/flutter_riverpod.dart';
import 'package:logger/logger.dart';
import 'package:th_cow_passport/services/farm/model/farm_model.dart';
import 'package:th_cow_passport/supabase_config.dart';

final logger = Logger();

final farmServiceProvider = Provider((ref) => FarmService());

final userFarmsProvider = FutureProvider.family<List<Farm>, String>((ref, userId) async {
  final farmService = ref.watch(farmServiceProvider);
  return farmService.getUserFarms(userId);
});

class FarmService {
  final _supabaseClient = supabase;
  static const String _tableName = 'farms';

  /// Get all farms for a specific user
  Future<List<Farm>> getUserFarms(String userId) async {
    try {
      logger.d('[FarmService] Fetching farms for user: $userId');
      
      final response = await _supabaseClient
          .from(_tableName)
          .select()
          .eq('user_id', userId)
          .order('created_at', ascending: false);

      if (response.isEmpty) {
        logger.i('[FarmService] No farms found for user: $userId');
        return [];
      }

      final farms = response.map((item) => Farm.fromMap(item)).toList();
      logger.i('[FarmService] Fetched ${farms.length} farms');
      return farms;
    } catch (e) {
      logger.e('[FarmService] Error fetching farms', error: e);
      throw Exception('Could not fetch farms.');
    }
  }

  /// Get a single farm by ID
  Future<Farm?> getFarmById(int farmId) async {
    try {
      final response = await _supabaseClient
          .from(_tableName)
          .select()
          .eq('id', farmId)
          .single();

      return Farm.fromMap(response);
    } catch (e) {
      logger.e('[FarmService] Error fetching farm', error: e);
      return null;
    }
  }

  /// Create a new farm
  Future<Farm?> createFarm({
    String? userId,
    required String farmName,
    required String province,
    String? address,
    String? subDistrict,
    String? district,
    String? postalCode,
    double? latitude,
    double? longitude,
  }) async {
    try {
      // Derive userId from current session if not provided
      final idToUse = userId ?? _supabaseClient.auth.currentSession?.user.id;
      if (idToUse == null) {
        logger.e('[FarmService] No authenticated session or userId provided for farm creation');
        throw Exception('ไม่มีการยืนยันตัวตน: กรุณาเข้าสู่ระบบก่อนสร้างฟาร์ม');
      }

      final farm = Farm(
        id: 0, // Will be generated by DB
        userId: idToUse,
        farmName: farmName,
        address: address,
        subDistrict: subDistrict,
        district: district,
        province: province,
        postalCode: postalCode,
        latitude: latitude,
        longitude: longitude,
        createdAt: DateTime.now(),
      );

      final response = await _supabaseClient
          .from(_tableName)
          .insert(farm.toMapForInsert())
          .select()
          .single();

      logger.i('[FarmService] Farm created: $farmName');
      return Farm.fromMap(response);
    } catch (e) {
      logger.e('[FarmService] Error creating farm', error: e);
      return null;
    }
  }
}
